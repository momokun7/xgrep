"""Generate the API section of npm/README.md from npm/index.d.ts.

index.d.ts is written by `napi build` from the doc comments in
npm/src/lib.rs, so the README follows the Rust source:

    python scripts/npm_readme.py          # rewrite the section
    python scripts/npm_readme.py --check  # exit 1 if it is out of date

Only the standard library is used, so CI can run it with any Python 3.
"""

import re
import sys
from pathlib import Path

NPM = Path(__file__).resolve().parent.parent / "npm"
BEGIN = "<!-- BEGIN API: generated by scripts/npm_readme.py from index.d.ts; do not edit -->"
END = "<!-- END API -->"


def parse(dts):
    """Return [(kind, name, doc, members)] for the class and interfaces.

    members are (doc, line) pairs in declaration order.
    """
    blocks = []
    doc = []
    in_doc = False
    current = None
    for raw in dts.splitlines():
        line = raw.strip()
        if in_doc:
            if line.endswith("*/"):
                in_doc = False
                line = line[:-2]
            doc.append(line.lstrip("*").strip())
            continue
        if line.startswith("/**"):
            body = line[3:]
            if body.endswith("*/"):
                doc = [body[:-2].strip()]
            else:
                doc = [body.strip()]
                in_doc = True
            continue
        text = " ".join(d for d in doc if d)
        m = re.match(r"export declare class (\w+)|export interface (\w+)", line)
        if m:
            kind = "class" if m.group(1) else "interface"
            current = (kind, m.group(1) or m.group(2), text, [])
            blocks.append(current)
        elif line == "}":
            current = None
        elif current is not None and line:
            current[3].append((text, line))
        doc = []
    return blocks


def ts_type(t):
    t = t.replace(" | undefined | null", "")
    return re.sub(r"Array<([^<>]+)>", r"\1[]", t)


def cell(text):
    return text.replace("|", "\\|")


def render(blocks):
    out = ["## API", ""]
    for kind, name, doc, members in blocks:
        if kind != "class":
            continue
        for mdoc, line in members:
            line = ts_type(line)
            if line.startswith("static "):
                title = f"`{name}.{line[len('static '):]}`"
            elif line.startswith("get "):
                m = re.match(r"get (\w+)\(\): (.+)", line)
                title = f"`xg.{m.group(1)}: {m.group(2)}` (getter)"
            else:
                title = f"`xg.{line}`"
            out += [f"### {title}", "", mdoc, ""]
    for kind, name, doc, members in blocks:
        if kind != "interface":
            continue
        head = "Option" if name.endswith("Options") else "Field"
        out += [f"### `{name}`", "", doc, "", f"| {head} | Type | Description |", "|---|---|---|"]
        for mdoc, line in members:
            m = re.match(r"(\w+)(\??): (.+)", line)
            field, opt, typ = m.groups()
            out.append(f"| `{field}{opt}` | `{ts_type(typ)}` | {cell(mdoc)} |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    check = "--check" in sys.argv[1:]
    readme_path = NPM / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    api = render(parse((NPM / "index.d.ts").read_text(encoding="utf-8")))
    start, end = readme.index(BEGIN), readme.index(END)
    updated = readme[: start + len(BEGIN)] + "\n\n" + api + "\n" + readme[end:]
    if updated == readme:
        return 0
    if check:
        print("npm/README.md is out of date; run: python scripts/npm_readme.py", file=sys.stderr)
        return 1
    readme_path.write_bytes(updated.encode("utf-8"))
    print("updated npm/README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
